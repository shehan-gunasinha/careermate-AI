-- CareerMate AI initial schema (PostgreSQL)

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name     VARCHAR(150) NOT NULL,
    email         VARCHAR(255) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(30)  NOT NULL DEFAULT 'JOB_SEEKER',
    enabled       BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE TABLE user_profiles (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT       NOT NULL,
    phone               VARCHAR(30),
    location            VARCHAR(150),
    headline            VARCHAR(200),
    career_objective    TEXT,
    employment_status   VARCHAR(30),
    years_of_experience INTEGER,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_user_profiles_user UNIQUE (user_id),
    CONSTRAINT fk_user_profiles_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE TABLE user_skills (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL,
    name       VARCHAR(80) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uk_user_skills UNIQUE (user_id, name),
    CONSTRAINT fk_user_skills_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE TABLE user_education (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT       NOT NULL,
    institution    VARCHAR(200) NOT NULL,
    degree         VARCHAR(200),
    field_of_study VARCHAR(200),
    start_year     INTEGER,
    end_year       INTEGER,
    description    VARCHAR(2000),
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_user_education_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE TABLE user_experience (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL,
    company     VARCHAR(200) NOT NULL,
    title       VARCHAR(200) NOT NULL,
    start_date  DATE,
    end_date    DATE,
    is_current  BOOLEAN      NOT NULL DEFAULT FALSE,
    description VARCHAR(4000),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_user_experience_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE TABLE user_preferences (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT      NOT NULL,
    preferred_industries TEXT,
    preferred_roles     TEXT,
    preferred_locations TEXT,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uk_user_preferences_user UNIQUE (user_id),
    CONSTRAINT fk_user_preferences_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE TABLE resumes (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT       NOT NULL,
    title             VARCHAR(200) NOT NULL,
    original_filename VARCHAR(255) NOT NULL,
    storage_path      VARCHAR(500) NOT NULL,
    content_type      VARCHAR(120) NOT NULL,
    size_bytes        BIGINT       NOT NULL,
    source            VARCHAR(20)  NOT NULL DEFAULT 'UPLOAD',
    extracted_text    TEXT,
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_resumes_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE TABLE resume_analysis (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resume_id           BIGINT      NOT NULL,
    overall_score       INTEGER     NOT NULL,
    section_scores      TEXT,
    strengths           TEXT,
    weaknesses          TEXT,
    missing_information TEXT,
    recommendations     TEXT,
    language_issues     TEXT,
    summary             TEXT,
    ai_powered          BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_resume_analysis_resume FOREIGN KEY (resume_id) REFERENCES resumes (id) ON DELETE CASCADE
);

CREATE TABLE jobs (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title                   VARCHAR(200)  NOT NULL,
    company_name            VARCHAR(200)  NOT NULL,
    company_logo_url        VARCHAR(1000),
    company_description     VARCHAR(2000),
    location                VARCHAR(200)  NOT NULL,
    industry                VARCHAR(100),
    employment_type         VARCHAR(30)   NOT NULL,
    work_arrangement        VARCHAR(30)   NOT NULL,
    experience_level        VARCHAR(30)   NOT NULL,
    salary_min              NUMERIC(14, 2),
    salary_max              NUMERIC(14, 2),
    salary_currency         VARCHAR(10),
    short_description       VARCHAR(600),
    description             TEXT          NOT NULL,
    responsibilities        TEXT,
    required_qualifications TEXT,
    preferred_qualifications TEXT,
    posted_date             DATE,
    deadline                DATE,
    application_url         VARCHAR(1000),
    source                  VARCHAR(40)   NOT NULL DEFAULT 'MANUAL',
    external_id             VARCHAR(200),
    fingerprint             VARCHAR(64)   NOT NULL,
    demo                    BOOLEAN       NOT NULL DEFAULT FALSE,
    active                  BOOLEAN       NOT NULL DEFAULT TRUE,
    last_synced_at          TIMESTAMPTZ,
    created_at              TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at              TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uk_jobs_fingerprint UNIQUE (fingerprint)
);

CREATE UNIQUE INDEX ux_jobs_source_external ON jobs (source, external_id) WHERE external_id IS NOT NULL;
CREATE INDEX idx_jobs_active_posted ON jobs (active, posted_date DESC);
CREATE INDEX idx_jobs_industry ON jobs (industry);
CREATE INDEX idx_jobs_location ON jobs (location);
CREATE INDEX idx_jobs_employment_type ON jobs (employment_type);
CREATE INDEX idx_jobs_experience_level ON jobs (experience_level);
CREATE INDEX idx_jobs_deadline ON jobs (deadline);

CREATE TABLE job_skills (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id     BIGINT      NOT NULL,
    skill      VARCHAR(80) NOT NULL,
    required   BOOLEAN     NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_job_skills_job FOREIGN KEY (job_id) REFERENCES jobs (id) ON DELETE CASCADE
);
CREATE INDEX idx_job_skills_job ON job_skills (job_id);
CREATE INDEX idx_job_skills_skill ON job_skills (lower(skill));

CREATE TABLE saved_jobs (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL,
    job_id     BIGINT      NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uk_saved_jobs UNIQUE (user_id, job_id),
    CONSTRAINT fk_saved_jobs_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_saved_jobs_job FOREIGN KEY (job_id) REFERENCES jobs (id) ON DELETE CASCADE
);

CREATE TABLE job_matches (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL,
    job_id      BIGINT      NOT NULL,
    score       INTEGER     NOT NULL,
    ai_powered  BOOLEAN     NOT NULL DEFAULT FALSE,
    detail      TEXT,
    computed_at TIMESTAMPTZ NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uk_job_matches UNIQUE (user_id, job_id),
    CONSTRAINT fk_job_matches_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_job_matches_job FOREIGN KEY (job_id) REFERENCES jobs (id) ON DELETE CASCADE
);

CREATE TABLE applications (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT       NOT NULL,
    job_id           BIGINT,
    job_title        VARCHAR(200) NOT NULL,
    company          VARCHAR(200) NOT NULL,
    application_date DATE,
    status           VARCHAR(30)  NOT NULL DEFAULT 'SAVED',
    application_url  VARCHAR(1000),
    contact_person   VARCHAR(200),
    interview_date   TIMESTAMP,
    notes            VARCHAR(4000),
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_applications_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_applications_job FOREIGN KEY (job_id) REFERENCES jobs (id) ON DELETE SET NULL
);
CREATE INDEX idx_applications_user_status ON applications (user_id, status);
CREATE INDEX idx_applications_interview ON applications (interview_date);

CREATE TABLE application_history (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT      NOT NULL,
    from_status    VARCHAR(30),
    to_status      VARCHAR(30) NOT NULL,
    note           VARCHAR(1000),
    changed_at     TIMESTAMPTZ NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_application_history_app FOREIGN KEY (application_id) REFERENCES applications (id) ON DELETE CASCADE
);
CREATE INDEX idx_application_history_app ON application_history (application_id);

CREATE TABLE notifications (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT        NOT NULL,
    type       VARCHAR(40)   NOT NULL,
    title      VARCHAR(200)  NOT NULL,
    message    VARCHAR(1000) NOT NULL,
    link       VARCHAR(300),
    is_read    BOOLEAN       NOT NULL DEFAULT FALSE,
    dedupe_key VARCHAR(150),
    created_at TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uk_notifications_dedupe UNIQUE (user_id, dedupe_key),
    CONSTRAINT fk_notifications_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);
CREATE INDEX idx_notifications_user_read ON notifications (user_id, is_read);

CREATE TABLE chat_conversations (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL,
    title      VARCHAR(200) NOT NULL,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_chat_conversations_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);
CREATE INDEX idx_chat_conversations_user ON chat_conversations (user_id, updated_at DESC);

CREATE TABLE chat_messages (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT        NOT NULL,
    sender          VARCHAR(20)   NOT NULL,
    content         VARCHAR(12000) NOT NULL,
    ai_powered      BOOLEAN       NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT fk_chat_messages_conversation FOREIGN KEY (conversation_id) REFERENCES chat_conversations (id) ON DELETE CASCADE
);
CREATE INDEX idx_chat_messages_conversation ON chat_messages (conversation_id, id);

CREATE INDEX idx_resumes_user ON resumes (user_id, created_at DESC);
CREATE INDEX idx_resume_analysis_resume ON resume_analysis (resume_id, created_at DESC);
CREATE INDEX idx_saved_jobs_user ON saved_jobs (user_id);
